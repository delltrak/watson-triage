SCENARIOS = [s01_refs_merged, s02_closes_reopened, s03_pr_open, s04_umbrella, s05_negated, s06_unchecked,
             s07_later_pr, s08_ci_failed, s09_closed, s11_bug_no_pr, s12_needs_info, s13_en_refs_merged]


def main():
    ensure_repo()
    state = load()
    state['repo'] = REPO
    for build in SCENARIOS:
        if build.__name__ in state:
            continue
        print(f'building {build.__name__} ...', flush=True)
        state[build.__name__] = build(state)
        save(state)
    main_sha = git('rev-parse', 'HEAD')
    state['main_ci'] = wait_ci(main_sha)
    save(state)
    print(json.dumps(state, indent=2))


if __name__ == '__main__':
    main()
