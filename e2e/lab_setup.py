#!/usr/bin/env python3
"""Build Watson's E2E fixture repo: one issue/PR set per use case.

Creates (if missing) the PRIVATE repo delltrak/watson-e2e-lab from e2e/lab/, then
the scenarios below. Idempotent: progress is kept in e2e/.lab-state.json, so a
rerun only builds what is missing. GitHub writes go ONLY to the lab repo.

Needs: gh (logged in with repo scope) and git. Usage: python3 e2e/lab_setup.py
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO = 'delltrak/watson-e2e-lab'
HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / 'lab'
STATE = HERE / '.lab-state.json'
CLONE = HERE / '.lab-clone'


def run(cmd, cwd=None, check=True):
    result = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if check and result.returncode:
        sys.exit(f'failed: {" ".join(cmd)}\n{result.stderr.strip()}')
    return result.stdout.strip()


def gh(*args, check=True):
    return run(['gh', *args], check=check)


def git(*args, check=True):
    return run(['git', *args], cwd=CLONE, check=check)


def load():
    return json.loads(STATE.read_text()) if STATE.exists() else {}


def save(state):
    STATE.write_text(json.dumps(state, indent=2) + '\n')


def ensure_repo():
    if subprocess.run(['gh', 'repo', 'view', REPO], capture_output=True).returncode:
        gh('repo', 'create', REPO, '--private',
           '--description', 'Watson E2E fixtures (generated by watson-triage/e2e; not for real work)')
    if not (CLONE / '.git').exists():
        run(['gh', 'repo', 'clone', REPO, str(CLONE)])
    if not git('ls-remote', '--heads', 'origin', 'main', check=False):
        shutil.copytree(TEMPLATE, CLONE, dirs_exist_ok=True)
        git('checkout', '-B', 'main')
        git('add', '-A')
        git('commit', '-m', 'Lab app with tests and CI')
        git('push', '-u', 'origin', 'main')
    git('checkout', 'main')
    git('pull', '--ff-only', 'origin', 'main')


def number_of(url):
    return int(url.strip().rstrip('/').rsplit('/', 1)[1])


def issue(title, body):
    return number_of(gh('issue', 'create', '-R', REPO, '--title', title, '--body', body))


def pull(branch, title, body, files, draft=False):
    git('checkout', 'main')
    git('pull', '--ff-only', 'origin', 'main')
    git('checkout', '-B', branch)
    for path, content in files.items():
        target = CLONE / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    git('add', '-A')
    git('commit', '-m', title)
    git('push', '-f', '-u', 'origin', branch)
    args = ['pr', 'create', '-R', REPO, '--base', 'main', '--head', branch, '--title', title, '--body', body]
    number = number_of(gh(*args, *(['--draft'] if draft else [])))
    git('checkout', 'main')
    return number


def head_sha(pr):
    return gh('pr', 'view', str(pr), '-R', REPO, '--json', 'headRefOid', '--jq', '.headRefOid')


def verdict(pr, text):
    sha = head_sha(pr)
    gh('pr', 'comment', str(pr), '-R', REPO, '--body', f'Revisão independente — commit `{sha[:7]}`\n\n{text}')


def merge(pr):
    gh('pr', 'merge', str(pr), '-R', REPO, '--squash', '--delete-branch')
    for _ in range(30):
        data = json.loads(gh('pr', 'view', str(pr), '-R', REPO, '--json', 'state,mergeCommit'))
        if data['state'] == 'MERGED' and data.get('mergeCommit'):
            git('checkout', 'main')
            git('pull', '--ff-only', 'origin', 'main')
            return data['mergeCommit']['oid']
        time.sleep(2)
    sys.exit(f'PR #{pr} did not merge')


def wait_ci(sha, timeout=600):
    deadline = time.time() + timeout
    while time.time() < deadline:
        runs = json.loads(gh('api', f'repos/{REPO}/actions/runs?head_sha={sha}',
                             '--jq', '[.workflow_runs[] | {status, conclusion}]'))
        if runs and all(r['status'] == 'completed' for r in runs):
            return [r['conclusion'] for r in runs]
        time.sleep(10)
    sys.exit(f'CI on {sha[:7]} did not finish in time')


def note(slug, text):
    return {f'docs/notes/{slug}.md': text + '\n'}


CUSTOMERS = '''"""Customer registration."""
from app.cpf import is_valid


class InvalidCPF(ValueError):
    pass


def register(db, name, cpf):
    """Save a customer; an invalid CPF is refused and nothing is saved."""
    if not is_valid(cpf):
        raise InvalidCPF('CPF inválido')
    db[cpf] = name
    return cpf
'''
