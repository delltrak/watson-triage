# ---------------------------------------------------------------- scenarios ----
def s01_refs_merged(state):
    """Merged PR says Refs #N, delivers exactly what the issue asks, trusted APROVAR verdict → suggest_close."""
    n = issue('Cadastro de clientes aceita CPF inválido',
              'Não existe validação de CPF no cadastro: qualquer número é salvo.\n\n'
              'Critério: criar app/customers.py com register(db, name, cpf) que recusa CPF inválido '
              '(dígitos verificadores, via app.cpf.is_valid) com a mensagem "CPF inválido" e não salva nada; '
              'CPF válido é salvo. Com testes.')
    pr = pull('e2e/s01-customers', 'Cadastro de clientes recusa CPF inválido',
              f'## Issue\n\nRefs #{n}\n\nregister() valida o CPF com app.cpf.is_valid antes de salvar.',
              {'app/customers.py': CUSTOMERS, 'tests/test_customers.py': CUSTOMERS_TESTS})
    verdict(pr, '**Veredito: APROVAR.**')
    return {'issue': n, 'pr': pr, 'merge': merge(pr)}


def s02_closes_reopened(state):
    """Merged PR says Closes #N; the issue was reopened after the merge → review_close."""
    n = issue('Desconto acima de 100% gera preço negativo',
              'Aplicar desconto de 120% no checkout gera preço negativo.')
    pr = pull('e2e/s02-discount-guard', 'Recusar desconto fora de 0 a 100',
              f'Closes #{n}\n\nA função apply já recusa percentuais fora do intervalo.',
              note('s02-discount', 'app.discount.apply recusa percentuais fora de 0-100.'))
    sha = merge(pr)
    for _ in range(30):
        if gh('issue', 'view', str(n), '-R', REPO, '--json', 'state', '--jq', '.state') == 'CLOSED':
            break
        time.sleep(2)
    time.sleep(2)
    gh('issue', 'reopen', str(n), '-R', REPO)
    return {'issue': n, 'pr': pr, 'merge': sha}


def s03_pr_open(state):
    """A trusted draft PR is still open → pr_open (never a duplicate draft)."""
    n = issue('Mostrar subtotal por item no carrinho', 'Cada linha do carrinho deve mostrar preço x quantidade.')
    pr = pull('e2e/s03-subtotal', 'Subtotal por item (em andamento)', f'Refs #{n}\n\nPrimeira versão.',
              note('s03-subtotal', 'Rascunho do subtotal por item.'), draft=True)
    return {'issue': n, 'pr': pr}


