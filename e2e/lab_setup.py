def s07_later_pr(state):
    """A later multi-issue merged PR also cites #N without closing it → review_close."""
    n = issue('Histórico de pedidos do cliente', 'O cliente deve ver os pedidos anteriores.')
    helper = issue('Paginação da lista de pedidos', 'A lista de pedidos precisa de paginação.')
    first = pull('e2e/s07-history', 'Histórico de pedidos', f'Refs #{n}',
                 note('s07-history', 'Tela de histórico de pedidos.'))
    first_merge = merge(first)
    time.sleep(2)
    later = pull('e2e/s07-history-pages', 'Histórico com paginação', f'Refs #{n}\nRefs #{helper}',
                 note('s07-history-pages', 'Paginação no histórico.'))
    return {'issue': n, 'helper': helper, 'pr': first, 'later_pr': later, 'merge': first_merge,
            'later_merge': merge(later)}


def s08_ci_failed(state):
    """Merged PR with Refs whose merge commit fails CI → review_close; main is fixed afterwards."""
    n = issue('Arredondar desconto para baixo', 'O desconto deveria arredondar para baixo, não para o mais próximo.')
    broken = ('"""Price discounts."""\n\n\ndef apply(price, percent):\n'
              '    """Price after a percentage discount (0-100)."""\n'
              '    return round(price * (100 - percent) / 100 - 1, 2)\n')
    pr = pull('e2e/s08-discount-rounding', 'Arredondamento do desconto', f'Refs #{n}',
              {'app/discount.py': broken})
    sha = merge(pr)
    conclusions = wait_ci(sha)
    # Restore main so the other scenarios keep a green default branch.
    shutil.copy(TEMPLATE / 'app' / 'discount.py', CLONE / 'app' / 'discount.py')
    git('add', '-A')
    git('commit', '-m', 'Restore discount.apply (lab fixture reset)')
    git('push', 'origin', 'main')
    return {'issue': n, 'pr': pr, 'merge': sha, 'merge_ci': conclusions}


